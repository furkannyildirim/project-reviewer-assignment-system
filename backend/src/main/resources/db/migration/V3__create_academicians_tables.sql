CREATE TABLE academicians
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name  VARCHAR(100) NOT NULL,
    email      VARCHAR(255) UNIQUE,
    phone      VARCHAR(30),
    title      VARCHAR(100)
);

CREATE TABLE academician_keywords
(
    academician_id BIGINT       NOT NULL,
    keyword        VARCHAR(255) NOT NULL,

    CONSTRAINT pk_academician_keywords
        PRIMARY KEY (academician_id, keyword),

    CONSTRAINT fk_academician_keywords_academician
        FOREIGN KEY (academician_id)
            REFERENCES academicians (id)
            ON DELETE CASCADE,

    CONSTRAINT chk_academician_keywords_not_blank
        CHECK (BTRIM(keyword) <> '')
);

CREATE INDEX idx_academician_keywords_keyword
    ON academician_keywords (LOWER(keyword));