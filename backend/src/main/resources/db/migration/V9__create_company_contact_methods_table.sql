CREATE TABLE company_contact_methods
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT       NOT NULL,
    type       VARCHAR(20)  NOT NULL,
    value      VARCHAR(255) NOT NULL,
    label      VARCHAR(100),
    is_primary BOOLEAN      NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_company_contact_methods_company
        FOREIGN KEY (company_id)
            REFERENCES companies (id)
            ON DELETE CASCADE,

    CONSTRAINT chk_company_contact_methods_type
        CHECK (type IN ('PHONE', 'EMAIL')),

    CONSTRAINT chk_company_contact_methods_value_not_blank
        CHECK (BTRIM(value) <> '')
);

CREATE INDEX idx_company_contact_methods_company_id
    ON company_contact_methods (company_id);

CREATE UNIQUE INDEX uq_company_contact_methods_primary_type
    ON company_contact_methods (company_id, type)
    WHERE is_primary = TRUE;

CREATE UNIQUE INDEX uq_company_contact_methods_email_value
    ON company_contact_methods (LOWER(value))
    WHERE type = 'EMAIL';

INSERT INTO company_contact_methods (
    company_id,
    type,
    value,
    label,
    is_primary
)
SELECT
    id,
    'EMAIL',
    email,
    NULL,
    TRUE
FROM companies
WHERE email IS NOT NULL
  AND BTRIM(email) <> '';

INSERT INTO company_contact_methods (
    company_id,
    type,
    value,
    label,
    is_primary
)
SELECT
    id,
    'PHONE',
    phone,
    NULL,
    TRUE
FROM companies
WHERE phone IS NOT NULL
  AND BTRIM(phone) <> '';

INSERT INTO company_contact_methods (
    company_id,
    type,
    value,
    label,
    is_primary
)
SELECT
    id,
    'PHONE',
    secondary_phone,
    NULL,
    FALSE
FROM companies
WHERE secondary_phone IS NOT NULL
  AND BTRIM(secondary_phone) <> '';
