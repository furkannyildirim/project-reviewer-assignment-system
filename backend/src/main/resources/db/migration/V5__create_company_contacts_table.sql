CREATE TABLE company_contacts
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT       NOT NULL,
    full_name  VARCHAR(200)  NOT NULL,
    position   VARCHAR(150),
    email      VARCHAR(255),
    phone      VARCHAR(30),
    is_primary BOOLEAN       NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_company_contacts_company
        FOREIGN KEY (company_id)
            REFERENCES companies (id)
            ON DELETE CASCADE,

    CONSTRAINT chk_company_contacts_full_name_not_blank
        CHECK (BTRIM(full_name) <> ''),

    CONSTRAINT chk_company_contacts_contact_method
        CHECK (
            NULLIF(BTRIM(email), '') IS NOT NULL
                OR NULLIF(BTRIM(phone), '') IS NOT NULL
            )
);

CREATE INDEX idx_company_contacts_company_id
    ON company_contacts (company_id);

CREATE UNIQUE INDEX uq_company_contacts_primary
    ON company_contacts (company_id)
    WHERE is_primary = TRUE;