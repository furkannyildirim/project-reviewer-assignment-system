CREATE TABLE projects
(
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id                      BIGINT       NOT NULL,
    created_by                      BIGINT       NOT NULL,
    name                            VARCHAR(255) NOT NULL,
    project_manager                 VARCHAR(255),
    start_date                      DATE,
    duration_months                 INTEGER,
    end_date                        DATE,
    category                        VARCHAR(255),
    sector                          VARCHAR(255),
    summary                         TEXT,
    research_and_development_nature TEXT,
    innovative_aspect               TEXT,
    main_technology_area            TEXT,
    project_detail                  TEXT,
    status                          VARCHAR(30)  NOT NULL DEFAULT 'DRAFT',
    source_file_id                  UUID,
    original_file_name              VARCHAR(255),
    storage_key                     VARCHAR(500),
    content_type                    VARCHAR(255),
    file_size                       BIGINT,
    created_at                      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                      TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_projects_company
        FOREIGN KEY (company_id)
            REFERENCES companies (id),

    CONSTRAINT fk_projects_created_by
        FOREIGN KEY (created_by)
            REFERENCES users (id),

    CONSTRAINT chk_projects_status
        CHECK (status IN ('DRAFT', 'AWAITING_REVIEWER', 'ACTIVE', 'COMPLETED', 'CANCELLED')),

    CONSTRAINT chk_projects_duration_months_positive
        CHECK (duration_months IS NULL OR duration_months > 0),

    CONSTRAINT chk_projects_file_size_non_negative
        CHECK (file_size IS NULL OR file_size >= 0)
);

CREATE INDEX idx_projects_company_id
    ON projects (company_id);

CREATE INDEX idx_projects_status
    ON projects (status);

CREATE TABLE project_keywords
(
    project_id BIGINT       NOT NULL,
    keyword    VARCHAR(255) NOT NULL,

    CONSTRAINT pk_project_keywords
        PRIMARY KEY (project_id, keyword),

    CONSTRAINT fk_project_keywords_project
        FOREIGN KEY (project_id)
            REFERENCES projects (id)
            ON DELETE CASCADE,

    CONSTRAINT chk_project_keywords_not_blank
        CHECK (BTRIM(keyword) <> '')
);

CREATE INDEX idx_project_keywords_keyword
    ON project_keywords (LOWER(keyword));

CREATE TABLE project_reviewer_assignments
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id     BIGINT      NOT NULL,
    academician_id BIGINT      NOT NULL,
    assigned_by    BIGINT      NOT NULL,
    status         VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    assigned_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at       TIMESTAMP WITH TIME ZONE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_project_reviewer_assignments_project
        FOREIGN KEY (project_id)
            REFERENCES projects (id),

    CONSTRAINT fk_project_reviewer_assignments_academician
        FOREIGN KEY (academician_id)
            REFERENCES academicians (id),

    CONSTRAINT fk_project_reviewer_assignments_assigned_by
        FOREIGN KEY (assigned_by)
            REFERENCES users (id),

    CONSTRAINT chk_project_reviewer_assignments_status
        CHECK (status IN ('ACTIVE', 'COMPLETED', 'REMOVED'))
);

CREATE INDEX idx_project_reviewer_assignments_project_id
    ON project_reviewer_assignments (project_id);

CREATE INDEX idx_project_reviewer_assignments_academician_id
    ON project_reviewer_assignments (academician_id);

CREATE INDEX idx_project_reviewer_assignments_status
    ON project_reviewer_assignments (status);

CREATE UNIQUE INDEX uq_project_reviewer_assignments_active_reviewer
    ON project_reviewer_assignments (project_id, academician_id)
    WHERE status = 'ACTIVE';
